JPEG_SOI = b"\xff\xd8"
JPEG_EOI = b"\xff\xd9"


def _jpeg_size(jpeg_bytes: bytes) -> tuple[int, int]:
    """Return ``(width, height)`` of a complete JPEG (Pillow-decoded)."""
    with Image.open(io.BytesIO(jpeg_bytes)) as image:
        return image.size


def _run_ffmpeg(*args: str) -> None:
    """Generate a fixture video with ffmpeg; raises when the call fails."""
    subprocess.run(
        ["ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", *args],
        check=True,
        capture_output=True,
    )


