class TestSceneGating:
    def test_hard_cut_produces_candidate_window(self, cut20: Path) -> None:
        result = _extract(cut20)  # pre=5, post=10

        assert len(result.candidates) >= 1
        covering = [c for c in result.candidates if c.t_start <= 5.0 and c.t_end >= 10.0]
        assert covering, f"no window covers the t=10 cut: {result.candidates}"
        for c in result.candidates:
            assert 0.0 <= c.t_start < c.t_end <= 20.0
            assert c.reasons

    def test_single_cut_window_is_exactly_pre_post(self, cut20: Path) -> None:
        # The lone cut at t=10 with pre=5 / post=10 yields exactly [5, 20].
        result = _extract(cut20)

        assert len(result.candidates) == 1
        c = result.candidates[0]
        assert (c.t_start, c.t_end) == (5.0, 20.0)
        assert c.reasons == ("scene",)

    def test_max_event_windows_keeps_highest_peak(self, multi30: Path) -> None:
        result = _extract(multi30, max_event_windows=1)

        assert len(result.candidates) == 1
        c = result.candidates[0]
        assert 0.0 <= c.t_start < c.t_end <= 30.0
        # All five cuts score 1.0 (tied); the tie-break keeps the earliest
        # window: first cut at t=5 with pre=5 / post=10 -> [0, 15].
        assert (c.t_start, c.t_end) == (0.0, 15.0)

    def test_windows_ordered_and_capped(self, multi30: Path) -> None:
        result = _extract(multi30, max_event_windows=10)

        assert len(result.candidates) == 5
        starts = [c.t_start for c in result.candidates]
        assert starts == sorted(starts)
        assert all(c.t_start < c.t_end for c in result.candidates)

    def test_close_triggers_merge_into_one_window(self, cut20: Path) -> None:
        # A zero pre/post window around the single cut stays [10, 10]...
        # which is degenerate and skipped; with a tiny post it is [10, 11].
        result = _extract(cut20, window_pre_seconds=0.0, window_post_seconds=0.0)
        assert result.candidates == ()
        tiny = _extract(cut20, window_pre_seconds=0.0, window_post_seconds=1.0)
        assert len(tiny.candidates) == 1
        assert tiny.candidates[0].t_start == 10.0

    def test_merge_gap_constant(self) -> None:
        assert MERGE_GAP_SECONDS == 1.0
        assert SCENE_THRESHOLD == 0.3


