class TestJpegQualityMapping:
    def test_endpoints(self) -> None:
        assert jpeg_quality_to_qv(60) == 31
        assert jpeg_quality_to_qv(95) == 2

    def test_monotonic_decreasing(self) -> None:
        values = [jpeg_quality_to_qv(q) for q in range(60, 96)]
        assert all(a >= b for a, b in zip(values, values[1:], strict=False))

    def test_clamped_out_of_range(self) -> None:
        assert jpeg_quality_to_qv(0) == 31
        assert jpeg_quality_to_qv(100) == 2
        assert all(2 <= jpeg_quality_to_qv(q) <= 31 for q in range(-20, 140))


