class TestFrameExtraction:
    def test_60s_clip_at_fps_2_yields_120_frames(self, clip60: Path) -> None:
        result = _extract(clip60, probe_fps=2.0)

        assert len(result.frames) == 120
        expected_times = [i / 2.0 for i in range(120)]
        assert [f.t_seconds for f in result.frames] == pytest.approx(expected_times)
        times = [f.t_seconds for f in result.frames]
        assert all(a < b for a, b in zip(times, times[1:], strict=False))
        for frame in result.frames:
            assert frame.jpeg_bytes[:2] == JPEG_SOI
            assert frame.jpeg_bytes[-2:] == JPEG_EOI
            assert len(frame.jpeg_bytes) > len(JPEG_SOI)

    def test_probe_fps_1_vs_2_frame_counts(self, clip60: Path) -> None:
        # Guards the fps filter wiring: frame count scales with probe_fps.
        assert len(_extract(clip60, probe_fps=1.0).frames) == 60
        assert len(_extract(clip60, probe_fps=2.0).frames) == 120

    def test_result_metadata(self, clip60: Path) -> None:
        result = _extract(clip60)
        assert isinstance(result, ExtractionResult)
        assert result.duration_seconds == pytest.approx(60.0, abs=0.1)
        assert result.elapsed_ms >= 0


