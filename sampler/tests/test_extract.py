#: ffmpeg log lines carry per-process memory addresses (``@ 0x...``) that
#: differ between invocations of the same command.
_ADDR_RE = re.compile(r" @ 0x[0-9a-fA-F]+")


def _scene_pass_stderr(video: Path) -> str:
    """ffmpeg stderr of the scene pass re-run on ``video`` (test oracle)."""
    proc = subprocess.run(
        [
            "ffmpeg",
            "-nostdin",
            "-hide_banner",
            "-loglevel",
            "info",
            "-i",
            str(video),
            "-vf",
            "fps=2,select='gte(scene,0)',metadata=print",
            "-f",
            "null",
            "-",
        ],
        capture_output=True,
    )
    return proc.stderr.decode("utf-8", "replace")


def _extract(path: str | Path, probe_fps: float = 2.0, **overrides: object) -> ExtractionResult:
    params: dict[str, object] = {
        "probe_fps": probe_fps,
        "window_pre_seconds": 5.0,
        "window_post_seconds": 10.0,
        "max_event_windows": 8,
        "jpeg_quality": 85,
    }
    params.update(overrides)
    return extract_frames(path, **params)  # type: ignore[arg-type]


