class TestEmptyAndErrors:
    def test_zero_frame_video_returns_empty_result(self, zeroframe: Path) -> None:
        result = _extract(zeroframe)

        assert result.frames == ()
        assert result.candidates == ()
        assert result.duration_seconds == 0.0
        assert result.elapsed_ms >= 0

    def test_missing_file_raises(self, tmp_path: Path) -> None:
        with pytest.raises(ExtractionFailed, match="not found"):
            _extract(tmp_path / "missing.mp4")

    def test_corrupt_file_raises_with_stderr_tail(self, corrupt: Path) -> None:
        with pytest.raises(ExtractionFailed) as excinfo:
            _extract(corrupt)
        # The message must carry the (non-empty) tail of ffmpeg's stderr.
        tail = _scene_pass_stderr(corrupt).strip()[-2000:]
        assert tail
        assert _ADDR_RE.sub("", tail) in _ADDR_RE.sub("", str(excinfo.value))

    def test_corrupt_file_leaves_no_temp_dirs(self, corrupt: Path) -> None:
        before = set(os.listdir(tempfile.gettempdir()))

        with pytest.raises(ExtractionFailed):
            _extract(corrupt)

        after = set(os.listdir(tempfile.gettempdir()))
        assert after <= before

    def test_decode_timeout_raises(self, clip60: Path) -> None:
        with pytest.raises(ExtractionFailed, match="timed out"):
            _extract(clip60, timeout_seconds=0.001)

    def test_invalid_parameters(self, clip60: Path) -> None:
        base: dict[str, object] = {
            "window_pre_seconds": 1.0,
            "window_post_seconds": 1.0,
            "max_event_windows": 1,
            "jpeg_quality": 85,
        }
        with pytest.raises(ValueError):
            extract_frames(clip60, probe_fps=0.0, **base)  # type: ignore[arg-type]
        with pytest.raises(ValueError):
            extract_frames(clip60, probe_fps=-2.0, **base)  # type: ignore[arg-type]
        with pytest.raises(ValueError):
            extract_frames(
                clip60,
                probe_fps=2.0,
                **{**base, "window_pre_seconds": -0.5},  # type: ignore[arg-type]
            )
        with pytest.raises(ValueError):
            extract_frames(
                clip60,
                probe_fps=2.0,
                **{**base, "window_post_seconds": -1.0},  # type: ignore[arg-type]
            )
        with pytest.raises(ValueError):
            extract_frames(
                clip60,
                probe_fps=2.0,
                **{**base, "max_event_windows": 0},  # type: ignore[arg-type]
            )


